def cena(t, primeira, titulo_cap):
    lay, kicker = t[0], t[1]
    c = {"layout": lay, "kicker": kicker}
    if lay == "barras":
        c["itens"], c["alturas"], nar = t[2], t[3], t[4]
    elif lay == "lista":
        c["itens"], nar = t[2], t[3]
    elif lay == "item":
        c["preco"], nar = t[2], t[3]
    else:
        c["sub"], nar = t[2], t[3]
    c["nar"] = nar
    if primeira:
        c["cap"] = titulo_cap
    else:
        c["sem_cap"] = True
    return c


